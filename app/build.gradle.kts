val localSigning = Properties().apply {
    val config = rootProject.file("signing.properties")
    if (config.isFile) config.inputStream().use { load(it) }
}
fun signingValue(property: String, environment: String): String? =
    providers.gradleProperty(environment).orNull
        ?: providers.environmentVariable(environment).orNull
        ?: localSigning.getProperty(property)

val releaseStoreFile = signingValue("storeFile", "MAGPIE_KEYSTORE_FILE")
val releaseStorePassword = signingValue("storePassword", "MAGPIE_KEYSTORE_PASSWORD")
val releaseKeyAlias = signingValue("keyAlias", "MAGPIE_KEY_ALIAS")
val releaseKeyPassword = signingValue("keyPassword", "MAGPIE_KEY_PASSWORD")
val hasReleaseSigning = listOf(
    releaseStoreFile, releaseStorePassword, releaseKeyAlias, releaseKeyPassword
).all { !it.isNullOrBlank() }

gradle.taskGraph.whenReady {
    if (!hasReleaseSigning && allTasks.any {
            it.project == project && it.name in listOf("assembleRelease", "packageRelease", "bundleRelease")
        }) {
        throw GradleException("Release signing is missing. Configure signing.properties (see signing.properties.example) or MAGPIE_KEYSTORE_* / MAGPIE_KEY_* environment variables.")
    }
}

